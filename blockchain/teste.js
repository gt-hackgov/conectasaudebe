const solc = require('solc'); const fs = require('fs'); const ganache = require('ganache'); const { ethers } = require('ethers'); const crypto = require('crypto');
const src = fs.readFileSync('AuditoriaFilaConectaSaude.sol', 'utf8');
const input = { language: 'Solidity', sources: { 'A.sol': { content: src } }, settings: { optimizer: { enabled: true, runs: 200 }, outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } } } };
const out = JSON.parse(solc.compile(JSON.stringify(input)));
(out.errors || []).forEach(e => console.log(e.severity, e.formattedMessage));
const c = out.contracts['A.sol'].AuditoriaFilaConectaSaude;
fs.writeFileSync('abi.json', JSON.stringify(c.abi, null, 1));
const log = []; const L = (s) => { console.log(s); log.push(s); };
const COR = ['VERMELHO','LARANJA','AMARELO','VERDE','AZUL'];
const sha = (o) => '0x' + crypto.createHash('sha256').update(JSON.stringify(o)).digest('hex');
(async () => {
  const provider = new ethers.BrowserProvider(ganache.provider({ logging: { quiet: true }, wallet: { totalAccounts: 3 } }));
  const [sec, upa, intruso] = await Promise.all([0,1,2].map(i => provider.getSigner(i)));
  const f = new ethers.ContractFactory(c.abi, c.evm.bytecode.object, sec);
  const ct = await f.deploy(); await ct.waitForDeployment(); const rc0 = await ct.deploymentTransaction().wait();
  L(`Contrato implantado em ${await ct.getAddress()} (gás: ${rc0.gasUsed})`);
  L(`Secretaria (dona): ${await sec.getAddress()}`);
  let t = await ct.autorizarUnidade(await upa.getAddress(), true); await t.wait();
  L(`[OK] Secretaria autorizou a UPA ${await upa.getAddress()}`);
  const ok = async (p, msg) => { try { const tx = await p; const r = await tx.wait(); L(`[OK] ${msg} (gás: ${r.gasUsed})`); return r; } catch (e) { L(`[ERRO INESPERADO] ${msg}: ${e.shortMessage || e.message}`); process.exitCode = 1; } };
  const falha = async (fn, args, msg) => { try { await fn.staticCall(...args); const tx = await fn(...args); await tx.wait(); L(`[FALHOU O TESTE] ${msg} deveria ser rejeitado`); process.exitCode = 1; } catch (e) { const d = e.revert ? `${e.revert.name}(${e.revert.args.join(', ')})` : (() => { try { const p = ct.interface.parseError(e.data); return `${p.name}(${p.args.join(', ')})`; } catch { return e.shortMessage || e.message; } })(); L(`[REJEITADO, como esperado] ${msg} → ${d}`); } };
  const u = ct.connect(upa);
  const chegadas = [[1,3],[2,2],[3,4],[4,3],[5,1],[6,2]];
  for (const [s, cor] of chegadas) await ok(u.registrarEntrada(s, cor, sha({ senha: s, cor, iniciais: 'X.Y.', sal: 'abc' + s })), `Entrada senha ${s} (${COR[cor]})`);
  let p = await ct.proximo(); L(`Próximo pela regra: senha ${p[0]} (${COR[Number(p[1])]})`);
  await ok(u.registrarEntrada(7, 0, sha({ senha: 7, cor: 0, iniciais: 'M.S.', sal: 'abc7' })), 'Entrada senha 7 (VERMELHO)');
  p = await ct.proximo(); L(`Próximo pela regra: senha ${p[0]} (${COR[Number(p[1])]})`);
  await falha(u.chamar, [1], 'Chamar a senha 1 (VERDE) antes da 7 (VERMELHO) — tentativa de furar a fila');
  await falha(ct.connect(intruso).registrarEntrada, [99, 4, sha({ x: 1 })], 'Endereço não autorizado registrando entrada');
  await falha(u.registrarEntrada, [2, 4, sha({ x: 2 })], 'Registrar de novo a senha 2');
  await falha(u.registrarEntrada, [50, 4, ethers.ZeroHash], 'Entrada sem hash do registro');
  await falha(ct.connect(upa).autorizarUnidade, [await intruso.getAddress(), true], 'UPA tentando autorizar outro endereço');
  const ordem = [];
  for (let i = 0; i < 7; i++) { const [s] = await ct.proximo(); await ok(u.chamar(s), `Chamada da senha ${s}`); ordem.push(Number(s)); }
  L(`Ordem de atendimento registrada: ${ordem.join(' → ')}`);
  await falha(u.chamar, [1], 'Chamar com a fila vazia');
  const h7 = sha({ senha: 7, cor: 0, iniciais: 'M.S.', sal: 'abc7' });
  L(`Auditor confere registro da senha 7 com o hash correto: ${await ct.conferirRegistro(7, h7)}`);
  L(`Auditor confere registro da senha 7 com dado adulterado: ${await ct.conferirRegistro(7, sha({ senha: 7, cor: 3, iniciais: 'M.S.', sal: 'abc7' }))}`);
  L(`Totais: entradas=${await ct.totalEntradas()} chamadas=${await ct.totalChamadas()}`);
  const evs = await ct.queryFilter(ct.filters.PacienteChamado());
  L(`Eventos PacienteChamado publicados: ${evs.length} (ex.: senha ${evs[0].args.senha}, cor ${COR[Number(evs[0].args.cor)]})`);
  const esperado = [7,5,2,6,1,4,3];
  L(JSON.stringify(ordem) === JSON.stringify(esperado) ? 'RESULTADO: ordem idêntica à do heap do back-end (7, 5, 2, 6, 1, 4, 3) ✔' : 'RESULTADO: ordem DIFERENTE do esperado ✘');
  fs.writeFileSync('saida_teste.txt', log.join('\n') + '\n');
})();
